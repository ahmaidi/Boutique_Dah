import java.awt.*;
import java.awt.font.*;
import java.awt.geom.*;
import java.awt.image.BufferedImage;
import java.io.File;
import java.nio.file.*;
import java.text.AttributedString;
import java.util.Locale;
import javax.imageio.ImageIO;

// Convert shaped Arabic glyphs into vector paths: no runtime font/text loading on launch.
class GenerateLaunchBrand {
    public static void main(String[] args) throws Exception {
        Font font = Font.createFont(Font.TRUETYPE_FONT, new File(args[0])).deriveFont(25f);
        AttributedString title = new AttributedString("بوتيك الداه");
        title.addAttribute(TextAttribute.FONT, font);
        title.addAttribute(TextAttribute.RUN_DIRECTION, TextAttribute.RUN_DIRECTION_RTL);
        Shape text = new TextLayout(title.getIterator(), new FontRenderContext(null, true, true)).getOutline(null);
        Rectangle2D bounds = text.getBounds2D();
        double top = 144 - (96 + 18 + bounds.getHeight()) / 2;
        Shape shaped = AffineTransform.getTranslateInstance(144 - bounds.getCenterX(), top + 114 - bounds.getY()).createTransformedShape(text);
        String parcel = "M256,117l132,73v146l-132,75l-132,-75V190zM124,190l132,76l132,-76M256,266v145M190,154l132,75v62";
        String xml = String.format(Locale.ROOT, """
            <!-- Generated by scripts/generate-launch-brand.mjs. Logo and Cairo Arabic title are one drawable. -->
            <vector xmlns:android="http://schemas.android.com/apk/res/android"
                android:width="288dp" android:height="288dp" android:viewportWidth="288" android:viewportHeight="288">
                <group android:translateX="96" android:translateY="%.3f" android:scaleX="0.1875" android:scaleY="0.1875">
                    <path android:fillColor="#145b47" android:pathData="M64,0h384a64,64 0,0 1,64 64v384a64,64 0,0 1,-64 64h-384a64,64 0,0 1,-64 -64v-384a64,64 0,0 1,64 -64z" />
                    <path android:fillColor="@android:color/transparent" android:strokeColor="#e3f4c7" android:strokeWidth="19" android:strokeLineJoin="round" android:pathData="%s" />
                </group>
                <path android:fillColor="#145b47" android:pathData="%s" />
            </vector>
            """, top, parcel, path(shaped));
        Files.writeString(Path.of(args[1]), xml);
        BufferedImage preview = new BufferedImage(360, 740, BufferedImage.TYPE_INT_RGB);
        Graphics2D g = preview.createGraphics();
        g.setColor(Color.decode("#f5f8f6")); g.fillRect(0, 0, 360, 740);
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.translate(180 - 144, 370 - 144);
        g.setColor(Color.decode("#145b47")); g.fill(shaped);
        g.translate(96, top); g.scale(.1875, .1875);
        g.fill(new RoundRectangle2D.Double(0, 0, 512, 512, 128, 128));
        g.setColor(Color.decode("#e3f4c7")); g.setStroke(new BasicStroke(19, BasicStroke.CAP_BUTT, BasicStroke.JOIN_ROUND));
        Path2D box = new Path2D.Double();
        box.moveTo(256,117); box.lineTo(388,190); box.lineTo(388,336); box.lineTo(256,411); box.lineTo(124,336); box.lineTo(124,190); box.closePath();
        box.moveTo(124,190); box.lineTo(256,266); box.lineTo(388,190);
        box.moveTo(256,266); box.lineTo(256,411); box.moveTo(190,154); box.lineTo(322,229); box.lineTo(322,291);
        g.draw(box); g.dispose();
        ImageIO.write(preview, "png", new File(args[2]));
        System.out.println("Generated one launch drawable containing both the parcel logo and shaped Arabic title.");
    }
    static String path(Shape shape) {
        StringBuilder result = new StringBuilder(); double[] values = new double[6];
        for (PathIterator it = shape.getPathIterator(null); !it.isDone(); it.next()) {
            int kind = it.currentSegment(values);
            result.append(new String[]{"M","L","Q","C","Z"}[kind]);
            int count = new int[]{2,2,4,6,0}[kind];
            for (int j=0; j<count; j++) result.append(String.format(Locale.ROOT, "%s%.3f", j == 0 ? "" : ",", values[j]));
        }
        return result.toString();
    }
}
